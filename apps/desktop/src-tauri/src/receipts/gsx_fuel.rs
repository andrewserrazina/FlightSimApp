//! GSX Pro "FUEL DELIVERY RECEIPT", single-currency layout, as issued by GSX Pro 4.0.x (verified
//! against a real receipt from KBOS, 2026-10-17; sanitized copy in fixtures/gsx/receipts).
//!
//! Structure relied on (all inside `div.invoice`):
//! - `.head .title h1` = "FUEL DELIVERY RECEIPT"; `.head .receipt-id-num` = receipt identifier;
//! - `.parties .party`: `.section-label` "A. PROVIDER:" / "B. RECEIVER:", name in `.name` (`.name .primary`);
//! - `table.product-info tr`: `td.info-label` / `td.info-value` pairs (PRODUCT TYPE, TOTAL VOLUME, UPLIFT
//!   DATE, UPLIFT LOCATION, METHOD OF TRANSFER, AIRCRAFT);
//! - `table.items tbody tr`: a plain row is a charge, `tr.tax-item` a tax, `tr.subtotal` / `tr.total`
//!   summary rows; cells `td.item` (with `.tax-reason`), `td.qty` (`.primary` / `.secondary`),
//!   `td.unit-price`, `td.amount`;
//! - `.foot` = "Generated by GSX".
//!
//! The dual-currency variant (`.fx-disclosure`, stacked `td.amount .primary/.secondary`) and the price
//! list (`body.price-list`) have not been seen in a real receipt, so they do not match this layout and
//! are reported as unsupported rather than parsed by guesswork.

use dom_query::Selection;

use super::fuel::{normalize, FuelLayout, FuelReceiptFields, Issue, LineKind, ReceiptDocument, ReceiptLine};
use super::money::{parse_amount, parse_decimal, PrintedDecimal};

pub const LAYOUT_ID: &str = "gsx-fuel-receipt-v1";

pub fn layout() -> FuelLayout {
    FuelLayout { id: LAYOUT_ID, matches, extract }
}

fn matches(d: &ReceiptDocument) -> bool {
    d.text("div.invoice .head .title h1").as_deref() == Some("FUEL DELIVERY RECEIPT")
        && d.count("div.invoice .head .receipt-id-num") == 1
        && d.count("div.invoice table.product-info") == 1
        && d.count("div.invoice table.items") == 1
        && d.text("div.invoice .foot").as_deref() == Some("Generated by GSX")
        // Variants not yet verified against a real receipt:
        && d.count(".fx-disclosure") == 0
        && d.count("table.items td.amount .secondary, table.items td.unit-price .secondary") == 0
        && d.count("body.price-list") == 0
}

fn text_of(s: &Selection) -> String {
    normalize(&s.text())
}

fn opt(s: String) -> Option<String> {
    (!s.is_empty()).then_some(s)
}

/// `5,147 gal` → (5147, "gal").
fn printed_quantity(text: &str) -> Option<(PrintedDecimal, String)> {
    let (n, unit) = text.trim().rsplit_once(' ')?;
    Some((parse_decimal(n)?, unit.to_string()))
}

fn extract(d: &ReceiptDocument) -> (FuelReceiptFields, Vec<Issue>) {
    let mut f = FuelReceiptFields { receipt_id: d.text("div.invoice .head .receipt-id-num"), ..Default::default() };
    let mut issues = Vec::new();
    let mut problem = |code: &'static str, message: String| issues.push(Issue { code, message });

    for party in d.select("div.invoice .parties .party").iter() {
        let label = text_of(&party.select(".section-label"));
        let primary = text_of(&party.select(".name .primary"));
        let name = if primary.is_empty() { text_of(&party.select(".name")) } else { primary };
        match label.as_str() {
            "A. PROVIDER:" => f.provider = opt(name),
            "B. RECEIVER:" => f.receiver = opt(name),
            other => problem("unknown_party", format!("unrecognised party section '{other}'")),
        }
    }

    let mut volume_text = None;
    for row in d.select("div.invoice table.product-info tr").iter() {
        let label = text_of(&row.select("td.info-label"));
        let value = text_of(&row.select("td.info-value"));
        match label.as_str() {
            "PRODUCT TYPE:" => match value.split_once(" @ ") {
                Some((product, density)) => {
                    f.product = opt(product.to_string());
                    f.quantities.density_text = opt(density.to_string());
                }
                None => f.product = opt(value),
            },
            "TOTAL VOLUME:" => volume_text = Some(value),
            "UPLIFT DATE:" => f.date_text = opt(value),
            "UPLIFT LOCATION:" => {
                f.airport = value.split_once(" - ").map(|(code, _)| code).filter(|c| c.len() == 4 && c.chars().all(|ch| ch.is_ascii_uppercase() || ch.is_ascii_digit())).map(str::to_string);
                f.location_text = opt(value);
            }
            "METHOD OF TRANSFER:" => f.transfer_method = opt(value),
            "AIRCRAFT:" => {
                if let Some((reg, ty)) = value.split_once(" - ") {
                    f.aircraft_registration = opt(reg.to_string());
                    f.aircraft_type = opt(ty.to_string());
                }
                f.aircraft_text = opt(value);
            }
            other => problem("unknown_product_field", format!("unrecognised product field '{other}'")),
        }
    }

    for row in d.select("div.invoice table.items tbody tr").iter() {
        let amount_text = text_of(&row.select("td.amount"));
        let Some(amount) = parse_amount(&amount_text) else {
            problem("unreadable_amount", format!("amount '{amount_text}' could not be read"));
            continue;
        };
        if row.has_class("subtotal") {
            f.subtotal = Some(amount);
            continue;
        }
        if row.has_class("total") {
            f.total = Some(amount);
            continue;
        }
        let kind = if row.has_class("tax-item") {
            LineKind::Tax
        } else if row.attr("class").map_or(true, |c| c.trim().is_empty()) {
            LineKind::Charge
        } else {
            problem("unknown_row", format!("unrecognised charges row class '{}'", row.attr("class").unwrap_or_default()));
            continue;
        };
        let item = row.select("td.item");
        let reason = text_of(&item.select(".tax-reason"));
        let full = text_of(&item);
        let description = full.strip_suffix(&reason).map(|s| s.trim().to_string()).filter(|_| !reason.is_empty()).unwrap_or(full);

        let qty_primary = text_of(&row.select("td.qty .primary"));
        let (quantity, unit) = match printed_quantity(&qty_primary) {
            Some((q, u)) => (Some(q), Some(u)),
            None => (None, None),
        };
        if kind == LineKind::Charge {
            if unit.as_deref() == Some("gal") {
                f.quantities.gallons = quantity.clone();
            }
            for secondary in row.select("td.qty .secondary").iter() {
                match printed_quantity(&text_of(&secondary)) {
                    Some((q, u)) if u == "lb" => f.quantities.pounds = Some(q),
                    Some((q, u)) if u == "kg" => f.quantities.kilograms = Some(q),
                    _ => problem("unknown_quantity", format!("unrecognised quantity '{}'", text_of(&secondary))),
                }
            }
        }
        let unit_price_text = opt(text_of(&row.select("td.unit-price")));
        let unit_price = unit_price_text.as_deref().and_then(|t| parse_amount(t.split_once('/').map_or(t, |(p, _)| p)));
        f.lines.push(ReceiptLine { kind, description, note: opt(reason), quantity, unit, unit_price_text, unit_price, amount });
    }

    // The volume is printed twice (product information and the charge line); they must agree.
    if let (Some(v), Some(g)) = (volume_text.as_deref(), f.quantities.gallons.as_ref()) {
        match v.strip_suffix(" Gallons").and_then(parse_decimal) {
            Some(total) if total.units == g.units && total.scale == g.scale => {}
            _ => problem("volume_mismatch", format!("TOTAL VOLUME '{v}' does not match the charged quantity '{}'", g.text)),
        }
    }
    (f, issues)
}
