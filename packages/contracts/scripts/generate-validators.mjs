// Compiles the canonical JSON Schemas into standalone ESM validator code.
// Generated ahead of time so the desktop webview never needs `unsafe-eval` in its CSP.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schemas", "v1");
const BASE = "https://schemas.flightsimapp.invalid/v1/";

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictTypes: false, // reading_* schemas narrow `value` across $ref boundaries
  code: { source: true, esm: true },
});
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".json")).sort()) {
  ajv.addSchema(JSON.parse(readFileSync(join(schemaDir, file), "utf8")));
}

const exportsMap = {
  validateTelemetryFrameV1: `${BASE}telemetry-frame.v1.schema.json`,
  validateConnectionStateV1: `${BASE}connection-state.v1.schema.json`,
  validateFlightEventV1: `${BASE}flight-event.v1.schema.json`,
  validateBridgeHealthV1: `${BASE}bridge-health.v1.schema.json`,
  validateGsxStateV1: `${BASE}gsx-state.v1.schema.json`,
  validateBridgeMessageV1: `${BASE}bridge-message.v1.schema.json`,
};

// Ajv's standalone output still pulls a few runtime helpers in with CommonJS `require`, which
// does not exist in the webview. Replace each known helper with an inline ESM equivalent and
// fail loudly on anything unknown so a schema change can never ship a broken bundle.
const RUNTIME_HELPERS = {
  "ajv/dist/runtime/ucs2length": `{ default: (s) => { let n = 0; for (const _ of s) n++; return n; } }`,
  "ajv/dist/runtime/equal": `{ default: function equal(a, b) {
    if (a === b) return true;
    if (a && b && typeof a === "object" && typeof b === "object") {
      if (Array.isArray(a) !== Array.isArray(b)) return false;
      const ka = Object.keys(a), kb = Object.keys(b);
      if (ka.length !== kb.length) return false;
      return ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && equal(a[k], b[k]));
    }
    return a !== a && b !== b;
  } }`,
};
const code = standaloneCode(ajv, exportsMap).replace(/require\("([^"]+)"\)/g, (_, mod) => {
  const helper = RUNTIME_HELPERS[mod];
  if (!helper) throw new Error(`Unhandled Ajv runtime require: ${mod}`);
  return `(${helper})`;
});
if (/\brequire\(/.test(code)) throw new Error("Generated validators still contain require()");
const outDir = join(root, "src", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "validators.js"), `// @ts-nocheck\n// GENERATED by scripts/generate-validators.mjs — do not edit.\n${code}`);
writeFileSync(
  join(outDir, "validators.d.ts"),
  `// GENERATED by scripts/generate-validators.mjs — do not edit.\n` +
    `export interface GeneratedValidator {\n  (data: unknown): boolean;\n  errors?: Array<{ instancePath: string; message?: string; keyword: string }> | null;\n}\n` +
    Object.keys(exportsMap).map((name) => `export declare const ${name}: GeneratedValidator;\n`).join(""),
);
console.log(`generated ${Object.keys(exportsMap).length} validators`);
